function [rawValue, formattedValue, hasValue] = valuationValue(inputValue)
rawValue = NaN;
formattedValue = "";
hasValue = false;

if isstruct(inputValue)
    if isfield(inputValue, "fmt") && ~isempty(inputValue.fmt)
        formattedValue = string(inputValue.fmt);
    end

    inputValue = yfinance.internal.unwrapYahooValue(inputValue);
end

if isnumeric(inputValue) && isscalar(inputValue) && ~isnan(inputValue)
    rawValue = double(inputValue);
    hasValue = true;

    if formattedValue == ""
        formattedValue = string(inputValue);
    end
end
